import { createHash } from "node:crypto";
import type { ProviderResultStatus } from "../types";

// Documented: the provider calls  GET /webhook?message=<message>  (GET is the primary format).
// POST form/JSON is accepted only as extra compatibility.
// NOT documented: the layout of `message`, and any signature/secret. Nothing here guesses either.

export interface WebhookInput {
  method: string;
  query: URLSearchParams;
  contentType: string | null;
  bodyText: string;
}

export interface ParsedWebhook {
  reffId: string;
  status: ProviderResultStatus;
  message: string | null;
}

/** GET query `message` first (primary); POST form/JSON body only as a compatibility fallback. */
export function extractMessage(input: WebhookInput): string | null {
  const fromQuery = input.query.get("message");
  if (fromQuery) return fromQuery;
  if (input.method.toUpperCase() !== "POST") return null;

  const ct = (input.contentType ?? "").toLowerCase();
  const body = input.bodyText.trim();
  if (!body) return null;

  if (ct.includes("application/x-www-form-urlencoded")) {
    return new URLSearchParams(body).get("message");
  }
  if (ct.includes("json") || body.startsWith("{")) {
    try {
      const j: unknown = JSON.parse(body);
      if (j && typeof j === "object" && "message" in j) {
        const m = (j as { message: unknown }).message;
        return typeof m === "string" ? m : null;
      }
    } catch {
      return null;
    }
  }
  return null;
}

/**
 * OUR reff_id format (generated by reserve_balance_and_create_transaction: 'TK' + 18 hex).
 * Finding it inside the message is correlation against our own data, not a guess about the
 * provider's message layout. A message that mentions zero or several distinct ids is rejected.
 */
const OUR_REFF_ID = /\bTK[0-9A-F]{18}\b/gi;

export function findOurReffId(message: string): string | null {
  const ids = new Set((message.match(OUR_REFF_ID) ?? []).map((s) => s.toUpperCase()));
  return ids.size === 1 ? [...ids][0]! : null;
}

export type StatusExtractor = (message: string) => ProviderResultStatus | null;

/**
 * TODO(sample): how success/failure is expressed inside `message` is unknown, so there are NO
 * extractors. Until one is added (from real example messages) every callback resolves to
 * status UNKNOWN and finalizes nothing. Do not add wording heuristics without real samples.
 */
export const STATUS_EXTRACTORS: readonly StatusExtractor[] = [];

export function parseWebhookMessage(
  message: string,
  extractors: readonly StatusExtractor[] = STATUS_EXTRACTORS,
): ParsedWebhook | null {
  const reffId = findOurReffId(message);
  if (!reffId) return null;

  const verdicts = new Set<ProviderResultStatus>();
  for (const ex of extractors) {
    const v = ex(message);
    if (v && v !== "UNKNOWN") verdicts.add(v);
  }
  // Conflicting extractors => refuse to decide.
  const status: ProviderResultStatus = verdicts.size === 1 ? [...verdicts][0]! : "UNKNOWN";
  return { reffId, status, message };
}

/** Optional corroboration: does the message mention the destination we sent? (digits only) */
export function mentionsDestination(message: string, destination: string): boolean {
  const digits = destination.replace(/\D/g, "");
  if (digits.length < 6) return message.includes(destination);
  return message.replace(/\D/g, "").includes(digits);
}

/** Stable fingerprint of a callback, so duplicates collapse onto one audit row. */
export function webhookDedupeKey(input: WebhookInput): string {
  const q = [...input.query.entries()].sort(([a], [b]) => a.localeCompare(b));
  return createHash("sha256")
    .update(JSON.stringify([input.method.toUpperCase(), q, input.bodyText]))
    .digest("hex");
}
